import { test, expect } from '@playwright/test';
import { starterWords } from '../src/data/words';

test('real learning attempt survives reload, resolves a mistake and drives statistics', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Мой словарь', exact: true }).click();
  await page.getByRole('button', { name: 'Добавить слово', exact: true }).click();
  await page.getByLabel('Немецкое слово').fill('Hund');
  await page.getByLabel('Перевод', { exact: true }).fill('собака');
  await page.getByRole('combobox', { name: 'Артикль', exact: true }).selectOption('der');
  await page.getByRole('combobox', { name: 'Набор', exact: true }).fill('E2E');
  await page.getByRole('button', { name: 'Сохранить слово', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Слово добавлено');
  await page.getByRole('button', { name: 'Изучение слов', exact: true }).click();
  await page.getByRole('combobox', { name: 'Набор', exact: true }).selectOption('E2E');
  await page.getByRole('button', { name: /Русский → немецкий/ }).click();
  await page.getByRole('button', { name: /Начать тренировку/ }).click();
  await page.getByRole('textbox', { name: 'Ваш ответ' }).fill('die Hund');
  await page.getByRole('button', { name: /Проверить/ }).click();
  await expect(page.getByRole('status')).toContainText('Нужно повторить');
  await page.reload();
  await page.getByRole('button', { name: 'Мои ошибки', exact: true }).click();
  await expect(page.getByText('Неразобранных ошибок: 1', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: /Разобрать ошибки/ }).click();
  await page.getByRole('textbox', { name: 'Ваш ответ' }).fill('der Hund');
  await page.getByRole('button', { name: /Проверить/ }).click();
  await expect(page.getByRole('status')).toContainText('Верно');
  await page.getByRole('button', { name: /Продолжить/ }).click();
  await page.getByRole('button', { name: 'Статистика', exact: true }).click();
  const metrics = page.locator('.metric-card');
  await expect(metrics.filter({ hasText: 'ответов всего' }).locator('strong')).toHaveText('2');
  await expect(metrics.filter({ hasText: 'правильных ответов' }).locator('strong')).toHaveText('50%');
  await expect(page.getByText('Получено', { exact: true })).toHaveCount(1);
  await page.reload();
  await page.getByRole('button', { name: 'Мои ошибки', exact: true }).click();
  await expect(page.getByText('Неразобранных ошибок: 0', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Мой словарь', exact: true }).click();
  const personal = page.getByTestId('dictionary-word').filter({ hasText: 'E2E' });
  await personal.getByRole('button', { name: 'Удалить Hund' }).click();
  await page.getByRole('button', { name: 'Удалить слово', exact: true }).click();
  await expect(personal).toHaveCount(0);
  await page.getByRole('button', { name: 'Статистика', exact: true }).click();
  await expect(page.locator('.metric-card').filter({ hasText: 'ответов всего' }).locator('strong')).toHaveText('2');
  await expect(page.locator('.metric-card').filter({ hasText: 'слов в практике' }).locator('strong')).toHaveText('0');
});

test('desktop and mobile screenshots contain complete fresh interface', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByRole('button', { name: 'Начать обучение' })).toBeVisible();
  await page.screenshot({ path: 'artifacts/screenshots/home-desktop.png', fullPage: true });
  await page.getByRole('button', { name: 'Мой словарь', exact: true }).click();
  expect(starterWords.length).toBeGreaterThanOrEqual(360);
  await expect(page.getByTestId('dictionary-word')).toHaveCount(starterWords.length);
  await page.screenshot({ path: 'artifacts/screenshots/dictionary-desktop.png' });
  await page.getByRole('button', { name: 'Настройки', exact: true }).click();
  await page.getByRole('combobox', { name: 'Тема оформления' }).selectOption('dark');
  await page.getByRole('button', { name: 'Сохранить настройки' }).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  await page.screenshot({ path: 'artifacts/screenshots/settings-dark.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Открыть меню' }).click();
  await page.getByRole('button', { name: 'Мой словарь', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Мой словарь', exact: true })).toBeVisible();
  const width = await page.evaluate(() => ({ client: document.documentElement.clientWidth, scroll: document.documentElement.scrollWidth }));
  expect(width.scroll).toBeLessThanOrEqual(width.client);
  await page.screenshot({ path: 'artifacts/screenshots/dictionary-mobile.png', animations: 'disabled' });
});
