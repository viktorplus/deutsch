import { _electron as electron, expect } from '@playwright/test';
import { createRequire } from 'node:module';
import { mkdir, stat } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { randomUUID } from 'node:crypto';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const profile = path.join(root, 'artifacts', `electron-smoke-${randomUUID()}`);
await mkdir(profile, { recursive: true });
const require = createRequire(import.meta.url);
const executablePath = require('electron');
const environment = { ...process.env, DEUTSCHMASTER_DATA_DIR: profile };
delete environment.ELECTRON_RUN_AS_NODE;
const launch = () => electron.launch({ executablePath, args: [root, `--user-data-dir=${path.join(profile, 'chromium')}`], cwd: root, env: environment, timeout: 60000 });
let app;
try {
  app = await launch();
  let page = await app.firstWindow();
  await expect(page.getByText('Офлайн · SQLite', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Мой словарь', exact: true }).click();
  await page.getByRole('button', { name: 'Добавить слово', exact: true }).click();
  await page.getByLabel('Немецкое слово').fill('Grüße');
  await page.getByLabel('Перевод', { exact: true }).fill('приветствия');
  await page.getByRole('combobox', { name: 'Набор', exact: true }).fill('Electron Smoke');
  await page.getByRole('button', { name: 'Сохранить слово', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Слово добавлено');
  await page.getByRole('button', { name: 'Изучение слов', exact: true }).click();
  await page.getByRole('combobox', { name: 'Набор', exact: true }).selectOption('Electron Smoke');
  await page.getByRole('button', { name: /Русский → немецкий/ }).click();
  await page.getByRole('button', { name: /Начать тренировку/ }).click();
  await page.getByRole('textbox', { name: 'Ваш ответ' }).fill('Grüße');
  await page.getByRole('button', { name: /Проверить/ }).click();
  await expect(page.getByRole('status')).toContainText('Верно');
  await page.getByRole('button', { name: 'Настройки', exact: true }).click();
  await page.getByLabel('Дневная цель, ответов').fill('7');
  await page.getByRole('button', { name: 'Сохранить настройки' }).click();
  await expect(page.getByRole('status')).toContainText('Настройки сохранены');
  await app.close(); app = undefined;
  expect((await stat(path.join(profile, 'deutschmaster.sqlite'))).size).toBeGreaterThan(0);
  app = await launch(); page = await app.firstWindow();
  await page.getByRole('button', { name: 'Настройки', exact: true }).click();
  await expect(page.getByLabel('Дневная цель, ответов')).toHaveValue('7');
  await page.getByRole('button', { name: 'Мой словарь', exact: true }).click();
  await page.getByLabel('Поиск по словарю').fill('Grüße');
  await expect(page.getByTestId('dictionary-word')).toContainText('приветствия');
  await page.getByRole('button', { name: 'Статистика', exact: true }).click();
  await expect(page.locator('.metric-card').filter({ hasText: 'ответов всего' }).locator('strong')).toHaveText('1');
  await expect(page.locator('.metric-card').filter({ hasText: 'правильных ответов' }).locator('strong')).toHaveText('100%');
  await page.screenshot({ path: path.join(profile, 'restart.png'), fullPage: true });
  console.log(`Electron SQLite save/restart passed. Isolated profile: ${profile}`);
} finally { if (app) await app.close(); }
